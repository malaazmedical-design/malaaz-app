#!/usr/bin/env python3
"""Builds 01_additive_safe.sql for the ORIGINAL project from the tested ReVoice files in ../test-project.
Only additive pieces are taken (new columns/tables/functions/policies). Anything that replaces or removes
original behaviour is left out and lives in 02_release_switch.sql / 03_security_hardening.sql."""
import re, pathlib
T = pathlib.Path(__file__).resolve().parent.parent / "test-project"
def rd(n): return (T / n).read_text(encoding="utf8")
def upto(s, marker): return s[: s.index(marker)]
def cut(s, start, end=None):
    i = s.index(start); j = s.index(end, i) if end else len(s)
    return s[:i] + s[j:]
out = []
def add(name, body): out.append(f"\n-- ======== from {name} ========\n{body.strip()}\n")

add("05_new_columns.sql", rd("05_new_columns.sql"))
add("07_register_client.sql", rd("07_register_client.sql"))
add("08_provider_app.sql", rd("08_provider_app.sql"))
add("09 (provider_price_for only)", upto(rd("09_quick_request_routing.sql"), "create or replace function public.create_booking_offers"))
add("10 (norm_ar only)", upto(rd("10_area_match_normalized.sql"), "create or replace function public.create_booking_offers"))
add("11 (push helpers only; original notify_* triggers are NOT replaced; pg_net already exists on the original)", upto(rd("11_push_notifications.sql"), "-- new offer -> push to that provider").replace("create extension if not exists pg_net with schema extensions;\n", ""))
add("13_phase1.sql", rd("13_phase1.sql"))
s = rd("14_ask_doctor_v2.sql")
for p in ("doctor_see_new_cases", "doctor_update_case", "patient_insert_case", "patient_own_cases"):
    s = s.replace(f"drop policy if exists {p} on public.ask_doctor_cases;\n", "")
s = s.replace("drop policy if exists attachments_access on public.ask_doctor_attachments;\ncreate policy attachments_access on",
              "drop policy if exists ask_att_rw on public.ask_doctor_attachments;\ncreate policy ask_att_rw on")
assert "attachments_access" not in s
add("14_ask_doctor_v2.sql (old ask_* policies kept; removed in 02)", s)
s = rd("15_online_consultation_chat.sql")
s = cut(s, "-- schedule it (pg_cron", "-- ───────── grants")
s = s.replace("create or replace function public.admin_consultations()", "drop function if exists public.admin_consultations();\ncreate or replace function public.admin_consultations()", 1)
add("15_online_consultation_chat.sql (cron removed -> 03)", s)
add("16_rtc_guard.sql", rd("16_rtc_guard.sql"))
add("17_voice_video_channels.sql", rd("17_voice_video_channels.sql"))
s = rd("19_missing_pieces.sql")
s = cut(s, "do $$ begin\n  begin perform cron.unschedule('ask-expire-tick')", "-- nursing: quick service")
s = upto(s, "-- nursing: quick service")
add("19 (ask_expire_tick only; cron -> 03, service rows -> 02)", s)
s = rd("22_admin_step6.sql")
s = s.replace('drop policy if exists "Allow auth all" on public.governorates;\n', "")
add('22_admin_step6.sql ("Allow auth all" is dropped later, in 03)', s)
add("23_english_names.sql", rd("23_english_names.sql"))
add("24_admin_set_appointment.sql", rd("24_admin_set_appointment.sql"))
add("25_appointment_time_reminders.sql", rd("25_appointment_time_reminders.sql"))
s = rd("26_summary_reminders.sql")
add("26 (cron removed -> 03)", cut(s, "do $$ begin\n  begin perform cron.unschedule('consultations-summary-tick')"))
for n in ("27_ratings_to_reviews_and_summary_admin.sql", "28_unpublish_rating.sql", "29_clock_starts_on_entry.sql",
          "30_edit_delete_messages.sql", "31_provider_name_en.sql", "32_install_attribution.sql",
          "33_delete_my_account.sql", "34_radiology_names_en.sql"):
    add(n, rd(n))
s = rd("35_stale_bookings.sql")
add("35_stale_bookings.sql (cron removed -> 02)", cut(s, "do $$ begin\n  begin perform cron.unschedule('stale-bookings-tick')"))
add("36_admin_push.sql", rd("36_admin_push.sql"))
s = rd("37_consult_doctor_first.sql")
add("37_consult_doctor_first.sql (cron removed -> 02)", cut(s, "do $$ begin\n  begin perform cron.unschedule('consultation-requests-tick')"))
add("38_unregister_push_on_logout.sql", rd("38_unregister_push_on_logout.sql"))

head = """-- ReVoice -> ORIGINAL project, step 1 of 3: ADDITIVE and SAFE. Generated by build.py (do not edit by hand).
-- Adds only: nullable columns, new tables, new functions (new names), extra permissive policies, new buckets.
-- Does NOT drop/replace any original function, trigger or policy, does NOT schedule cron, does NOT insert services.
-- Idempotent: running it twice is harmless. Run on a COPY first, then on the original only after explicit approval.
begin;
"""
(pathlib.Path(__file__).parent / "01_additive_safe.sql").write_text(head + "".join(out) + "\ncommit;\n", encoding="utf8")
print("ok")

# ---------------------------------------------------------------- 02: release switch (changes behaviour of the original app)
o2 = []
def add2(name, body): o2.append(f"\n-- ======== from {name} ========\n{body.strip()}\n")
s9 = rd("09_quick_request_routing.sql"); s10 = rd("10_area_match_normalized.sql")
# order matters: 09 defines the wave-1/wave-2 routing, 10 replaces create_booking_offers with the normalized-area version
add2("09 (create_booking_offers v1 is skipped: superseded by 10) accept_booking_offer + get_offer_details + escalation radius",
     s9[s9.index("-- escalation after 10 minutes"):])
add2("10 create_booking_offers (normalized Arabic area matching)", s10[s10.index("create or replace function public.create_booking_offers"):])
add2("12_online_consultation.sql (online consultation service row)", rd("12_online_consultation.sql"))
s = rd("18_step4.sql"); add2("18 (nursing stay options)", s[s.index("insert into public.sub_services"):] if "insert into public.sub_services" in s else "")
s = rd("19_missing_pieces.sql"); add2("19 (nursing quick service + x-ray rows)", s[s.index("-- nursing: quick service"):])
s = rd("14_ask_doctor_v2.sql")
add2("ask-a-doctor v2: remove the OLD policies so only the new rules apply", """drop policy if exists doctor_see_new_cases on public.ask_doctor_cases;
drop policy if exists doctor_update_case on public.ask_doctor_cases;
drop policy if exists patient_insert_case on public.ask_doctor_cases;
drop policy if exists patient_own_cases on public.ask_doctor_cases;
drop policy if exists attachments_access on public.ask_doctor_attachments;""")
cron = """do $$ begin
  begin perform cron.unschedule('consultations-tick'); exception when others then null; end;
  perform cron.schedule('consultations-tick', '* * * * *', 'select public.consultations_tick()');
  begin perform cron.unschedule('consultations-summary-tick'); exception when others then null; end;
  perform cron.schedule('consultations-summary-tick', '* * * * *', 'select public.consultations_summary_tick()');
  begin perform cron.unschedule('ask-expire-tick'); exception when others then null; end;
  perform cron.schedule('ask-expire-tick', '*/15 * * * *', 'select public.ask_expire_tick()');
  begin perform cron.unschedule('stale-bookings-tick'); exception when others then null; end;
  perform cron.schedule('stale-bookings-tick', '*/10 * * * *', 'select public.stale_bookings_tick()');
  begin perform cron.unschedule('consultation-requests-tick'); exception when others then null; end;
  perform cron.schedule('consultation-requests-tick', '* * * * *', 'select public.consultation_requests_tick()');
end $$;"""
add2("cron jobs for consultations + ask-a-doctor expiry (pg_cron already exists on the original)", cron)
head2 = """-- ReVoice -> ORIGINAL project, step 2 of 3: RELEASE SWITCH. Run only when the new app is about to ship (after 01).
-- This CHANGES behaviour the old app sees: booking routing/price on accept, ask-a-doctor access rules, new service rows, cron jobs.
-- Generated by build.py (do not edit by hand). Idempotent. Run on a copy first.
begin;
"""
(pathlib.Path(__file__).parent / "02_release_switch.sql").write_text(head2 + "".join(o2) + "\ncommit;\n", encoding="utf8")
print("02 ok")
